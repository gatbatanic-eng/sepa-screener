const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const root = {innerHTML:'',querySelectorAll:()=>[],addEventListener:()=>{}};
const records = new Map();
const context = vm.createContext({document:{querySelector:()=>root,addEventListener:()=>{}},localStorage:{getItem:k=>records.get(k)||null,setItem:(k,v)=>records.set(k,v)}});
vm.runInContext(fs.readFileSync('docs/market/watchlist222.js','utf8'),context);
const stock = code => ({code,name:'종목'+code,sector:'테스트',changePct:5,turnoverKRW:2e10,turnoverVs20d:2,providerNewsCount:5,score:50,sourceUrl:'https://example.com',evidence:[]});
const a=stock('A'),b=stock('B'),c=stock('C');
const report = {date:'20261022',watchlist222:{selectedCount:2,purpose:'검토용',coverage:{evaluated:3,marketCollected:700,scope:'sector_leaders_only'},groups:[{id:'market',title:'주도',items:[],missingReason:'미확인'},{id:'domestic',title:'국내',items:[],missingReason:'미확인'},{id:'individual',title:'개별',items:[a,b],missingReason:'미확인'}],reviewPool:[a,b,c],limitations:[],rules:{score:'테스트 점수'}}};
context.renderWatchlist222(report);
context.event222({target:{dataset:{action:'pick',group:'market',index:'0'},value:'A'}});
assert(root.innerHTML.includes('중복 선정할 수 없습니다'));
assert.equal(records.size,0,'duplicate choice must not be persisted');
context.event222({target:{dataset:{action:'pick',group:'market',index:'0'},value:'C'}});
assert.equal(JSON.parse(records.get('golden222:20261022')).groups.market[0],'C');
for(const [field,value] of [['entry','100'],['stop','95'],['target','110']])context.event222({target:{dataset:{action:'plan',code:'C',field},value}});
assert(root.innerHTML.includes('계획 손익비 2.00 : 1'));
context.event222({target:{dataset:{action:'note',code:'C'},value:'<img src=x onerror=alert(1)>'}});
assert(root.innerHTML.includes('&lt;img'));
assert(!root.innerHTML.includes('<img src=x'));
context.event222({target:{dataset:{action:'confirm',code:'C'},checked:true}});
assert.equal(JSON.parse(records.get('golden222:20261022')).confirmed.C,true);
context.event222({target:{dataset:{action:'zero',code:'C'}}});
assert.equal(JSON.parse(records.get('golden222:20261022')).zero,'C');
context.renderWatchlist222({...report,date:'20261021'});
assert(!root.innerHTML.includes('&lt;img'),'drafts must be isolated by report date');
console.log('UI draft smoke: duplicate guard, replacement, risk/reward, escaping, confirmation, priority and date isolation OK');
